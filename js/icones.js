// <svg> référençant le sprite ; `label` → icône porteuse de sens, sinon décorative (aria-hidden)
export function icone(nom, { label = '', classe = '' } = {}) {
  const a11y = label ? `role="img" aria-label="${label.replace(/"/g, '&quot;')}"` : 'aria-hidden="true" focusable="false"'
  return `<svg class="ic${classe ? ' ' + classe : ''}" ${a11y}><use href="#i-${nom}"/></svg>`
}

// Injecte le sprite une fois par page (les <use href="#i-…"> du HTML statique s'y résolvent)
export function injecterSprite() {
  if (document.getElementById('sprite-icones')) return
  const symboles = Object.entries(TRACES).map(([nom, d]) =>
    `<symbol id="i-${nom}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${d}</symbol>`).join('')
  document.body.insertAdjacentHTML('afterbegin',
    `<svg id="sprite-icones" xmlns="http://www.w3.org/2000/svg" style="display:none">${symboles}</svg>`)
}
